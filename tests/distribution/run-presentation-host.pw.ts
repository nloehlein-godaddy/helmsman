import { expect, test } from '@playwright/test';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { fixture, sourceRoot } from './isolated-fixture';

test('installed viewer and history use selected aliases and a scoped auxiliary session in the source-denied shell', async ({ page }, testInfo) => {
  test.setTimeout(120_000);
  const host = await fixture({ distribution: process.env.HELMSMAN_PRESENTATION_TEST_DISTRIBUTION });
  host.env.REPO_PROJECT_MAP = 'org/a=TASK,org/b=OTHER';
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  try {
    await expect(host.script('prove-presentation-isolation.mjs', `import { readFileSync } from 'node:fs'; readFileSync(${JSON.stringify(join(sourceRoot, 'src/main.ts'))});`)).rejects.toThrow('Source checkout is unavailable');
    await host.installAuthorPackage('plugin-sources/run-viewer', 'example.run-viewer');
    await host.installAuthorPackage('plugin-sources/run-history', 'example.run-history');
    await host.cli('select', 'helmsman/run-viewer-page', 'example.run-viewer/page');
    await host.cli('select', 'helmsman/run-history-page', 'example.run-history/page');
    const dbUrl = pathToFileURL(join(host.app, 'server/helmsman/db.js')).href;
    await host.script('seed-presentation.mjs', `import { openDb } from ${JSON.stringify(dbUrl)};
      const db=openDb(process.env.HELMSMAN_DB); try {
        for(let i=0;i<55;i++) db.insertRun({id:'run-'+i,repo:'org/a',ticketId:'TASK-'+i,adapter:'codex',status:'succeeded',attempt:2,prNumber:null,startedAt:new Date(Date.UTC(2026,8,20,12,0,i)).toISOString(),endedAt:'2026-09-20T13:00:00.000Z',costUsd:null,worktreePath:null});
        db.insertRun({id:'foreign-run',repo:'org/b',ticketId:'OTHER-1',adapter:'codex',status:'succeeded',attempt:1,prNumber:null,startedAt:'2026-09-20T12:00:00.000Z',endedAt:'2026-09-20T13:00:00.000Z',costUsd:null,worktreePath:null});
        for(let i=0;i<350;i++) db.appendEvent('run-54','log','Visible Unicode 🛟 log '+i,'2026-09-20T12:00:00.000Z');
        db.appendEvent('foreign-run','log','Explicit org/b log','2026-09-20T12:00:00.000Z');
      } finally {db.close();}`);
    const origin = await host.start();
    await page.goto(`${origin}/run-history?repo=org/a`);
    const history = page.locator('[data-plugin-page="example.run-history/page"]');
    await expect(history.getByRole('heading', { name: 'Voyage history', exact: true })).toBeVisible();
    await expect(history.getByText(/55 matching runs observed/)).toBeVisible();
    await expect(history.locator('[data-run-id]')).toHaveCount(50);
    await history.getByRole('button', { name: 'Next page', exact: true }).click();
    await expect(history.locator('[data-run-id]')).toHaveCount(5);
    await history.getByRole('button', { name: 'Previous page', exact: true }).click();
    await expect(history.locator('[data-run-id]')).toHaveCount(50);
    await history.getByRole('button', { name: 'TASK-54', exact: true }).click();
    const viewer = page.locator('.plugin-auxiliary-slot [data-plugin-page="example.run-viewer/page"]');
    await expect(viewer.getByRole('heading', { name: 'Voyage viewer', exact: true })).toBeVisible();
    await expect(viewer.locator('.run-log')).toContainText('log 349');
    await expect.poll(() => viewer.evaluate(element => document.activeElement === element.closest('[data-auxiliary-page]'))).toBe(true);
    await expect(page.locator('.repo-select')).toHaveValue('org/a');
    await expect(page).toHaveURL(/\/run-history\?.*run=run-54.*runRepo=org%2Fa/);
    await viewer.getByRole('button', { name: 'Earlier logs', exact: true }).click();
    await expect(viewer.locator('.run-log')).toContainText('log 250');
    await expect(viewer.getByRole('button', { name: 'Follow latest', exact: true })).toBeVisible();
    await page.evaluate(() => { Object.defineProperty(document, 'hidden', { configurable: true, value: true }); document.dispatchEvent(new Event('visibilitychange')); });
    await expect(viewer.getByRole('button', { name: 'Follow latest', exact: true, includeHidden: true })).toBeDisabled();
    await page.evaluate(() => { Object.defineProperty(document, 'hidden', { configurable: true, value: false }); document.dispatchEvent(new Event('visibilitychange')); });
    await expect(viewer.getByRole('button', { name: 'Follow latest', exact: true })).toBeEnabled();
    await expect(viewer.locator('.run-log')).toContainText('log 250');
    await viewer.evaluate(element => element.scrollIntoView({ block: 'start' }));
    await page.screenshot({ path: testInfo.outputPath('run-presentation-desktop.png') });
    await page.setViewportSize({ width: 390, height: 844 });
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await viewer.evaluate(element => element.scrollIntoView({ block: 'start' }));
    await page.screenshot({ path: testInfo.outputPath('run-presentation-mobile.png') });
    const content = page.locator('.page-content');
    const scrollBefore = await content.evaluate(element => element.scrollTop);
    await viewer.locator('.run-log').scrollIntoViewIfNeeded();
    await expect(viewer.locator('.run-log')).toBeInViewport();
    await expect.poll(() => content.evaluate(element => element.scrollTop)).toBeGreaterThan(scrollBefore);
    await page.screenshot({ path: testInfo.outputPath('run-presentation-mobile-logs.png') });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto(`${origin}/run-history?repo=org/a&run=foreign-run&runRepo=org/b`);
    await expect(viewer.locator('.run-log')).toContainText('Explicit org/b log');
    await expect(page.locator('.repo-select')).toHaveValue('org/a');
    await page.reload();
    await expect(viewer.locator('.run-log')).toContainText('Explicit org/b log');
    await expect(page.locator('.repo-select')).toHaveValue('org/a');
    await page.goto(`${origin}/run-viewer?repo=org/a&run=foreign-run`);
    await expect(page.locator('section.plugin-run-viewer')).toContainText('Selected run is unavailable in this scope.');
    await expect(page.locator('.run-log')).toHaveCount(0);
    await host.cli('disable', 'example.run-viewer');
    await page.goto(`${origin}/run-viewer?repo=org/a&run=run-54&runRepo=org/a`);
    await expect(page.locator('[data-plugin-page="helmsman.run-viewer/page"]')).toHaveCount(0);
    await expect(page.getByText('This page is unavailable. Choose another view or restore its plugin.', { exact: false })).toBeVisible();
    expect(errors).toEqual([]);
    expect(host.output()).not.toContain('Source checkout is unavailable');
  } finally { await host.close(); }
});
